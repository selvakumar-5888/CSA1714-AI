"""Task 6 - Exhaustive search vs 2-opt hill climbing with random restarts for the delivery tour."""
import itertools, json, math, random, time, statistics as st
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def dist_matrix(pts):
    n = len(pts)
    return [[math.dist(pts[i], pts[j]) for j in range(n)] for i in range(n)]


def exhaustive(D):
    """Tour = permutation of customers 1..n-1 with the depot 0 fixed as start/end -> (n-1)! candidates.
    Generated by depth-first extension of a partial tour; cost accumulated incrementally; best retained."""
    n = len(D)
    best = [math.inf, None]
    count = [0]
    path = [0]
    used = [False] * n
    used[0] = True

    def rec(cost):
        if len(path) == n:
            count[0] += 1
            total = cost + D[path[-1]][0]
            if total < best[0]:
                best[0], best[1] = total, path[:]
            return
        last = path[-1]
        for c in range(1, n):
            if not used[c]:
                used[c] = True; path.append(c)
                rec(cost + D[last][c])
                path.pop(); used[c] = False
    rec(0.0)
    return best[0], best[1], count[0]


def tour_len(D, t):
    return sum(D[t[i]][t[(i + 1) % len(t)]] for i in range(len(t)))


def two_opt(D, tour):
    n = len(tour)
    improved = True
    while improved:
        improved = False
        for i in range(1, n - 1):
            for j in range(i + 1, n):
                a, b = tour[i - 1], tour[i]
                c, d = tour[j], tour[(j + 1) % n]
                if D[a][c] + D[b][d] < D[a][b] + D[c][d] - 1e-12:
                    tour[i:j + 1] = reversed(tour[i:j + 1])
                    improved = True
    return tour


def local_search(D, restarts, rng):
    n = len(D)
    best = math.inf
    for _ in range(restarts):
        t = list(range(1, n)); rng.shuffle(t)
        t = two_opt(D, [0] + t)
        best = min(best, tour_len(D, t))
    return best


if __name__ == "__main__":
    out = {}
    # --- correctness: points on a circle (convex position) -> optimum is the polygon perimeter
    m = 9
    pts = [(math.cos(2 * math.pi * i / m), math.sin(2 * math.pi * i / m)) for i in range(m)]
    random.Random(3).shuffle(pts)
    D = dist_matrix(pts)
    best, tour, cnt = exhaustive(D)
    perim = m * 2 * math.sin(math.pi / m)
    bf = min(tour_len(D, [0] + list(p)) for p in itertools.permutations(range(1, m)))
    print(f"Correctness: exhaustive={best:.6f}  analytic perimeter={perim:.6f}  itertools brute force={bf:.6f} tours={cnt}")
    out["correctness"] = dict(n=m, exhaustive=best, perimeter=perim, bruteforce=bf, tours=cnt)
    # 5-point hand-checkable instance: unit square corners + centre depot offset -> optimum 4 (square tour)
    sq = [(0, 0), (1, 0), (1, 1), (0, 1)]
    Dsq = dist_matrix(sq)
    b4, t4, c4 = exhaustive(Dsq)
    print("Unit square: best =", b4, "tour =", t4, "tours =", c4)
    out["square"] = dict(best=b4, tour=t4, tours=c4)

    # --- growth
    growth = []
    for n in range(5, 12):
        rng = random.Random(n)
        pts = [(rng.random(), rng.random()) for _ in range(n)]
        D = dist_matrix(pts)
        t0 = time.perf_counter()
        b, t, c = exhaustive(D)
        dt = time.perf_counter() - t0
        row = dict(n=n, predicted=math.factorial(n - 1), counted=c, time_s=dt, us_per_tour=dt / c * 1e6)
        growth.append(row); print(row)
    out["growth"] = growth

    # --- local search quality (known optimum), 3 instances x 20 runs for each n and each restart setting
    quality = []
    for n in (8, 9, 10):
        for restarts in (1, 10):
            gaps, times, hits = [], [], 0
            for inst in range(3):
                rng = random.Random(100 * n + inst)
                pts = [(rng.random(), rng.random()) for _ in range(n)]
                D = dist_matrix(pts)
                opt = exhaustive(D)[0]
                for run in range(20):
                    r = random.Random(run + 7)
                    t0 = time.perf_counter()
                    L = local_search(D, restarts, r)
                    times.append(time.perf_counter() - t0)
                    gap = (L - opt) / opt * 100
                    gaps.append(gap); hits += gap < 1e-9
            row = dict(n=n, restarts=restarts, runs=60, mean_gap=st.mean(gaps), max_gap=max(gaps),
                       optimum_hit_rate=hits / 60, mean_time_ms=st.mean(times) * 1000)
            quality.append(row); print(row)
    out["quality"] = quality

    # --- local search on sizes where exhaustive is impossible
    big = []
    for n in (15, 20, 50, 100):
        rng = random.Random(n)
        pts = [(rng.random(), rng.random()) for _ in range(n)]
        D = dist_matrix(pts)
        t0 = time.perf_counter(); L = local_search(D, 10, random.Random(1)); dt = time.perf_counter() - t0
        big.append(dict(n=n, length=L, time_s=dt, exhaustive_tours=math.factorial(n - 1)))
        print(big[-1])
    out["big"] = big
    json.dump(out, open("../results/task6.json", "w"), indent=1)

    fig, ax = plt.subplots(figsize=(5.2, 3.3))
    ax.semilogy([g["n"] for g in growth], [g["counted"] for g in growth], "o-", label="tours enumerated (n-1)!")
    ax.semilogy([g["n"] for g in growth], [g["time_s"] for g in growth], "s-", label="time (s)")
    ax.set_xlabel("customers n (incl. depot)"); ax.legend(fontsize=7)
    plt.tight_layout(); plt.savefig("../figs/fig8_task6.png", dpi=130)
